CREATE TABLE IF NOT EXISTS users(
id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,email TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL,
role TEXT NOT NULL DEFAULT 'candidate' CHECK(role IN('candidate','admin')),created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS jobs(
id INTEGER PRIMARY KEY AUTOINCREMENT,title TEXT NOT NULL,company TEXT,description TEXT NOT NULL,required_skills TEXT NOT NULL,
created_by INTEGER NOT NULL,created_at TEXT NOT NULL,FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS resumes(
id INTEGER PRIMARY KEY AUTOINCREMENT,user_id INTEGER NOT NULL,filename TEXT NOT NULL,extracted_text TEXT NOT NULL,skills TEXT,
ats_score REAL DEFAULT 0,uploaded_at TEXT NOT NULL,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS applications(
id INTEGER PRIMARY KEY AUTOINCREMENT,user_id INTEGER NOT NULL,job_id INTEGER NOT NULL,resume_id INTEGER NOT NULL,
status TEXT NOT NULL DEFAULT 'Applied',applied_at TEXT NOT NULL,UNIQUE(user_id,job_id),
FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE CASCADE,
FOREIGN KEY(resume_id) REFERENCES resumes(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS match_results(
id INTEGER PRIMARY KEY AUTOINCREMENT,application_id INTEGER NOT NULL UNIQUE,semantic_score REAL DEFAULT 0,skill_score REAL DEFAULT 0,
overall_score REAL DEFAULT 0,matched_skills TEXT,missing_skills TEXT,suggestions TEXT,ats_score REAL DEFAULT 0,created_at TEXT NOT NULL,
FOREIGN KEY(application_id) REFERENCES applications(id) ON DELETE CASCADE);
